import { randomBytes } from 'node:crypto'
import { expect, test, type Page } from '@playwright/test'

async function login(page: Page, username: string, password: string) {
  await page.getByLabel('Логин').fill(username)
  await page.getByLabel('Пароль').fill(password)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
}
async function nav(page: Page, name: string) {
  await page.getByRole('navigation').getByRole('link', { name, exact: true }).click()
}

test('manager registers a concert and finances through the browser', async ({ page }) => {
  test.skip(!process.env.E2E_ADMIN_LOGIN || !process.env.E2E_ADMIN_PASSWORD || !process.env.E2E_BASE_URL,
    'Start the isolated PostgreSQL scenario with e2e/run.py')
  const password = randomBytes(24).toString('base64url')
  await page.goto('/')
  await login(page, process.env.E2E_ADMIN_LOGIN!, process.env.E2E_ADMIN_PASSWORD!)
  await expect(page.getByRole('heading', { name: 'Пользователи' })).toBeVisible()
  await expect(page.getByRole('navigation').getByRole('link', { name: 'Концерты' })).toHaveCount(0)
  const user = page.getByRole('region', { name: 'Новый пользователь' })
  await user.getByLabel('ФИО').fill('Тестовый менеджер')
  await user.getByLabel('Должность').fill('Менеджер')
  await user.getByLabel('Логин').fill('frontend_manager')
  await user.getByLabel('Пароль').fill(password)
  await user.getByLabel('Роли').selectOption('MANAGER')
  await user.getByRole('button', { name: 'Создать пользователя' }).click()
  await expect(page.getByRole('heading', { name: 'Тестовый менеджер' })).toBeVisible()
  await page.getByRole('button', { name: 'Выйти' }).click()
  await login(page, 'frontend_manager', password)
  await expect(page.getByRole('heading', { name: 'Концерты', exact: true })).toBeVisible()
  await expect(page.getByRole('navigation').getByRole('link', { name: 'Пользователи' })).toHaveCount(0)

  const denied = await page.request.post('/api/venue', {
    data: { name: 'CSRF forbidden', city: 'Moscow', address: 'Address' },
  })
  expect(denied.status()).toBe(403)
  await nav(page, 'Площадки')
  const venue = page.getByRole('region', { name: 'Новая запись' })
  await venue.getByLabel('Название').fill('Тестовый зал')
  await venue.getByLabel('Город').fill('Москва')
  await venue.getByLabel('Адрес').fill('Тестовая улица, 1')
  await venue.getByRole('button', { name: 'Добавить', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Тестовый зал' })).toBeVisible()

  await nav(page, 'Контрагенты')
  const party = page.getByRole('region', { name: 'Новая запись' })
  await party.getByLabel('Название').fill('Тестовый организатор')
  await party.getByLabel('Тип контрагента').fill('LEGAL')
  await party.getByRole('button', { name: 'Добавить', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Тестовый организатор' })).toBeVisible()

  await nav(page, 'Категории операций')
  for (const [code, name, direction] of [['FEE', 'Гонорар', 'IN'], ['TRAVEL', 'Транспорт', 'OUT']]) {
    const category = page.getByRole('region', { name: 'Новая запись' })
    await category.getByLabel('Код').fill(code)
    await category.getByLabel('Название').fill(name)
    await category.getByLabel('Направление').selectOption(direction)
    await category.getByRole('button', { name: 'Добавить', exact: true }).click()
    await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
  }

  await nav(page, 'Концерты')
  await page.getByRole('link', { name: 'Создать концерт' }).click()
  await page.getByLabel('Название').fill('Контрольный концерт')
  await page.getByLabel('Начало *', { exact: true }).fill('2020-01-01T18:00')
  await page.getByLabel('Окончание').fill('2020-01-01T20:00')
  await page.getByLabel('Площадка').selectOption({ label: 'Тестовый зал · Москва' })
  await page.getByLabel('Организатор').selectOption({ label: 'Тестовый организатор' })
  await page.getByLabel('Ответственный').selectOption({ label: 'Тестовый менеджер' })
  await page.getByLabel('Плановый бюджет').fill('100000')
  await page.getByRole('button', { name: 'Создать концерт' }).click()
  await expect(page.getByRole('heading', { name: 'Контрольный концерт' })).toBeVisible()
  await page.getByRole('button', { name: 'Подтвердить концерт' }).click()
  await expect(page.getByRole('alert')).toContainText('ACTIVE MAIN_SHOW')
  await page.getByRole('button', { name: 'Договоры' }).click()
  const contract = page.getByRole('region', { name: 'Новый договор' })
  await contract.getByLabel('Номер договора').fill('SHOW-001')
  await contract.getByLabel('Дата подписания').fill('2020-01-01')
  await contract.getByLabel('Предмет').fill('Выступление')
  await contract.getByLabel('Сумма договора').fill('500000')
  await contract.getByRole('button', { name: 'Создать договор' }).click()
  const show = page.getByRole('region', { name: 'SHOW-001' })
  await show.getByRole('button', { name: 'Активировать договор' }).click()
  await expect(show).toContainText('Действует')
  await page.getByRole('button', { name: 'Общее' }).click()
  await page.getByRole('button', { name: 'Подтвердить концерт' }).click()
  await expect(page.getByRole('status')).toHaveText('Подтверждён')

  await page.getByRole('button', { name: 'Финансовый журнал' }).click()
  const operation = page.getByRole('region', { name: 'Новая операция' })
  for (const [direction, category, amount, basis] of [
    ['IN', 'Гонорар · IN', '150000', 'Оплата организатора'],
    ['OUT', 'Транспорт · OUT', '40000', 'Транспортные расходы'],
  ]) {
    await operation.getByLabel('Вид операции').selectOption(direction)
    await operation.getByLabel('Категория').selectOption({ label: category })
    if (direction === 'IN') await operation.getByLabel('Договор').selectOption({ label: 'SHOW-001 · IN' })
    await operation.getByLabel('Дата операции').fill('2020-01-10')
    await operation.getByLabel('Сумма операции').fill(amount)
    await operation.getByLabel('Основание').fill(basis)
    await operation.getByRole('button', { name: 'Учесть операцию' }).click()
    await expect(page.getByRole('heading', { name: basis, exact: true })).toBeVisible()
    await expect(operation.getByLabel('Сумма операции')).toHaveValue('')
  }
  await page.getByRole('main').getByRole('link', { name: 'Финансовый отчёт' }).click()
  await page.getByLabel('Начало периода').fill('2020-01-01')
  await page.getByLabel('Конец периода').fill('2020-01-31')
  await page.getByLabel('Дата среза').fill('2020-01-31')
  await page.getByRole('button', { name: 'Сформировать отчёт' }).click()
  await expect(page.getByTestId('net-result')).toHaveText('110\u202f000,00 ₽')
  await expect(page.getByRole('row', { name: /SHOW-001/ })).toContainText('350\u202f000,00 ₽')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Финансовый отчёт' })).toBeVisible()

  await nav(page, 'Концерты')
  await page.getByRole('link', { name: 'Контрольный концерт' }).click()
  await page.getByRole('button', { name: 'Договоры' }).click()
  await contract.getByLabel('Номер договора').fill('SERVICE-001')
  await contract.getByLabel('Дата подписания').fill('2020-01-01')
  await contract.getByLabel('Вид договора').selectOption('SERVICE')
  await contract.getByLabel('Предмет').fill('Транспорт')
  await contract.getByLabel('Сумма договора').fill('40000')
  await contract.getByRole('button', { name: 'Создать договор' }).click()
  await expect(page.getByRole('heading', { name: 'SERVICE-001' })).toBeVisible()
  await page.getByRole('button', { name: 'Подрядчики' }).click()
  await page.getByLabel('Подрядчик').selectOption({ label: 'Тестовый организатор' })
  await page.getByLabel('Описание работы').fill('Перевозка оборудования')
  await page.getByLabel('Срок').fill('2020-01-02T12:00')
  await page.getByLabel('Согласованная стоимость').fill('40000')
  await page.getByRole('button', { name: 'Добавить работу' }).click()
  await page.getByLabel('Договор на работы').selectOption({ label: 'SERVICE-001 · 40\u202f000,00 ₽' })
  await page.getByRole('button', { name: 'Согласовать работу' }).click()
  await page.getByRole('button', { name: 'Отметить выполнение' }).click()
  await expect(page.getByText(/Выполнено · 40/)).toBeVisible()

  await page.getByRole('button', { name: 'Финансовый журнал' }).click()
  const receipt = page.getByRole('region', { name: 'Оплата организатора' })
  await receipt.getByText('Возврат', { exact: true }).click()
  await receipt.getByLabel('Дата возврата').fill('2020-01-11')
  await receipt.getByLabel('Сумма возврата').fill('10000')
  await receipt.getByLabel('Основание возврата').fill('Частичный возврат')
  await receipt.getByRole('button', { name: 'Учесть возврат' }).click()
  await expect(page.getByRole('heading', { name: 'Частичный возврат' })).toBeVisible()
  const cost = page.getByRole('region', { name: 'Транспортные расходы' })
  await cost.getByText('Аннулирование', { exact: true }).click()
  await cost.getByLabel('Причина аннулирования').fill('Ошибочная запись')
  await cost.getByRole('button', { name: 'Аннулировать операцию' }).click()
  await expect(cost).toContainText('Аннулирована')
  await page.getByRole('main').getByRole('link', { name: 'Финансовый отчёт' }).click()
  await page.getByLabel('Начало периода').fill('2020-01-01')
  await page.getByLabel('Конец периода').fill('2020-01-31')
  await page.getByLabel('Дата среза').fill('2020-01-31')
  await page.getByRole('button', { name: 'Сформировать отчёт' }).click()
  await expect(page.getByTestId('net-result')).toHaveText('140\u202f000,00 ₽')
  await expect(page.getByRole('row', { name: /SHOW-001/ })).toContainText('360\u202f000,00 ₽')

  await nav(page, 'Аналитика')
  await page.getByRole('button', { name: 'Показать рейтинг' }).click()
  await expect(page.getByText('Концертов в выборке: 0')).toBeVisible()
  await page.getByLabel('Планируемый концерт').selectOption({ label: 'Контрольный концерт' })
  await page.getByRole('button', { name: 'Рассчитать прогноз' }).click()
  await expect(page.getByText('Для прогноза нужно не менее 10 пригодных наблюдений.')).toBeVisible()
  await page.getByRole('button', { name: 'Выйти' }).click()
  await expect(page.getByRole('heading', { name: 'Вход' })).toBeVisible()
  expect((await page.request.get('/api/auth/me')).status()).toBe(401)
})
